export function templateText(value: TemplateText | undefined, locale: AppLocale): string {
  if (value === undefined) return '';
  if (typeof value === 'string') {
    if (locale === 'tr' && templateConfigTr[value]) return templateConfigTr[value];
    return value;
  }
  if (locale === 'zh-CN') return value.zh;
  if (locale === 'zh-TW') return createTraditionalMessages({ text: value.zh }).text;
  if (locale === 'tr') {
    if (value.tr) return value.tr;
    if (value.en && templateConfigTr[value.en]) return templateConfigTr[value.en];
    if (value.zh && templateConfigTr[value.zh]) return templateConfigTr[value.zh];
    return value.en;
  }
  return locale === 'ja' ? value.ja ?? value.en : value.en;
}

